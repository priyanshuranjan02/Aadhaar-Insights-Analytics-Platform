"""
Forecasting dashboard for Aadhaar Insights.

Displays the legacy analytics pipeline and the separately evaluated
experimental V2 pipeline. V2 projections are historical experiments based
on the available data ending in December 2025; they are not current forecasts.
"""

import os
import sys
from pathlib import Path

import pandas as pd
import plotly.express as px
import streamlit as st

APP_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
ROOT_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "../.."))

sys.path.insert(0, APP_DIR)
sys.path.insert(0, ROOT_DIR)

from src.config import PROCESSED_DATA_DIR  # noqa: E402


# =============================================================================
# Page configuration and constants
# =============================================================================

st.set_page_config(
    page_title="Forecasting",
    page_icon="📈",
    layout="wide",
)

st.title("📈 Forecasting")
st.caption("Machine Learning Forecasting and Predictive Analytics")

ANALYTICS_DIR = Path(PROCESSED_DATA_DIR) / "analytics"
V2_ROOT_DIR = Path(ROOT_DIR) / "data" / "processed" / "forecasting_v2"

DATASETS = ["enrolment", "demographic", "biometric"]


# =============================================================================
# Sidebar and legacy data loading
# =============================================================================

st.sidebar.header("Forecast Settings")
dataset = st.sidebar.selectbox("Dataset", DATASETS)
dataset_dir = ANALYTICS_DIR / dataset


def load_csv(directory: Path, filename: str) -> pd.DataFrame:
    """Load a CSV file, returning an empty frame if it is unavailable."""
    filepath = directory / filename
    if not filepath.exists():
        return pd.DataFrame()
    try:
        return pd.read_csv(filepath)
    except (OSError, pd.errors.ParserError, UnicodeDecodeError) as exc:
        st.warning(f"Could not read `{filepath.name}`: {exc}")
        return pd.DataFrame()


metrics_df = load_csv(dataset_dir, "model_metrics.csv")
forecast_df = load_csv(dataset_dir, "forecast_month.csv")
importance_df = load_csv(dataset_dir, "feature_importance.csv")
prediction_df = load_csv(dataset_dir, "actual_vs_predicted.csv")


# =============================================================================
# Legacy forecasting results
# =============================================================================

st.header("Legacy Forecasting Results")
st.caption(
    "These charts and metrics are generated by the original analytics pipeline. "
    "They are displayed separately from the experimental V2 evaluation."
)

if metrics_df.empty:
    st.warning(
        "Legacy forecasting results were not found for this dataset. "
        "Run the original forecasting pipeline to generate them."
    )
else:
    required_metric_columns = {"Model", "R2", "RMSE"}
    missing_metric_columns = required_metric_columns - set(metrics_df.columns)

    if missing_metric_columns:
        st.error(
            "The legacy model metrics file is missing required columns: "
            + ", ".join(sorted(missing_metric_columns))
        )
    else:
        best = metrics_df.iloc[0]
        best_model = str(best["Model"])
        best_r2 = pd.to_numeric(best["R2"], errors="coerce")
        best_rmse = pd.to_numeric(best["RMSE"], errors="coerce")
        forecast_horizon = len(forecast_df)

        card1, card2, card3, card4 = st.columns(4)
        card1.metric("Legacy Selected Model", best_model)
        card2.metric(
            "Legacy R²",
            f"{best_r2:.4f}" if pd.notna(best_r2) else "N/A",
        )
        card3.metric(
            "Legacy RMSE",
            f"{best_rmse:.6f}" if pd.notna(best_rmse) else "N/A",
        )
        card4.metric("Legacy Forecast Rows", forecast_horizon)

        st.divider()

        # Model performance
        st.subheader("📊 Model Performance")
        display_metrics = metrics_df.copy()
        format_map = {
            column: "{:.6f}"
            for column in ["MAE", "MSE", "RMSE"]
            if column in display_metrics.columns
        }
        if "MAPE" in display_metrics.columns:
            format_map["MAPE"] = "{:.2f}"
        if "R2" in display_metrics.columns:
            format_map["R2"] = "{:.4f}"

        try:
            styled_metrics = display_metrics.style
            if "R2" in display_metrics.columns:
                styled_metrics = styled_metrics.highlight_max(
                    subset=["R2"], color="#d4edda"
                )
            if "RMSE" in display_metrics.columns:
                styled_metrics = styled_metrics.highlight_min(
                    subset=["RMSE"], color="#d4edda"
                )
            if format_map:
                styled_metrics = styled_metrics.format(format_map)
            st.dataframe(styled_metrics, use_container_width=True)
        except (KeyError, ValueError):
            st.dataframe(display_metrics, use_container_width=True)

        st.divider()

        # Actual vs predicted
        st.subheader("🎯 Actual vs Predicted")
        if prediction_df.empty:
            st.info("Legacy prediction results are not available.")
        elif {"Actual", "Predicted"}.issubset(prediction_df.columns):
            plot_df = prediction_df.copy()
            max_points = 2000
            if len(plot_df) > max_points:
                step = max(len(plot_df) // max_points, 1)
                plot_df = plot_df.iloc[::step].copy()

            plot_df = plot_df.reset_index(drop=True)
            plot_df["Sample"] = plot_df.index + 1
            fig = px.line(
                plot_df,
                x="Sample",
                y=["Actual", "Predicted"],
                title="Legacy Actual vs Predicted Values",
            )
            fig.update_layout(
                xaxis_title="Samples",
                yaxis_title="Activity",
                hovermode="x unified",
                legend_title="Series",
                height=500,
            )
            st.plotly_chart(fig, use_container_width=True)
            st.caption(
                f"Displaying {len(plot_df):,} sampled observations from "
                f"{len(prediction_df):,} total predictions."
            )
        else:
            st.warning(
                "The legacy prediction file does not contain both "
                "`Actual` and `Predicted` columns."
            )

        st.divider()

        # Future forecast
        st.subheader("📈 Future Forecast")
        if forecast_df.empty:
            st.info("Legacy forecast data is not available.")
        elif {"date_month", "prediction"}.issubset(forecast_df.columns):
            fig = px.line(
                forecast_df,
                x="date_month",
                y="prediction",
                markers=True,
                title="Legacy Future Forecast",
            )
            fig.update_layout(
                xaxis_title="Forecast period",
                yaxis_title="Forecast activity",
                hovermode="x unified",
                height=450,
            )
            st.plotly_chart(fig, use_container_width=True)
        else:
            st.warning(
                "The legacy forecast file does not contain the expected "
                "`date_month` and `prediction` columns."
            )

        st.divider()

        # Feature importance
        st.subheader("📌 Top Feature Importance")
        if importance_df.empty:
            st.info("Legacy feature importance is not available.")
        elif {"Feature", "Importance"}.issubset(importance_df.columns):
            top_features = (
                importance_df.head(20)
                .sort_values("Importance", ascending=True)
            )
            fig = px.bar(
                top_features,
                x="Importance",
                y="Feature",
                orientation="h",
                title="Top 20 Legacy Feature Importances",
            )
            fig.update_layout(
                xaxis_title="Importance",
                yaxis_title="Feature",
                height=650,
            )
            st.plotly_chart(fig, use_container_width=True)
        else:
            st.warning(
                "The feature importance file does not contain the expected "
                "`Feature` and `Importance` columns."
            )

        st.divider()

        # Error analysis
        st.subheader("📉 Error Analysis")
        if prediction_df.empty or "Residual" not in prediction_df.columns:
            st.info("Legacy residual data is not available.")
        else:
            residuals = pd.to_numeric(
                prediction_df["Residual"], errors="coerce"
            ).dropna()
            if residuals.empty:
                st.info("No valid residual values are available.")
            else:
                residual_df = pd.DataFrame({"Residual": residuals})
                fig = px.histogram(
                    residual_df,
                    x="Residual",
                    nbins=50,
                    title="Legacy Residual Distribution",
                )
                fig.update_layout(
                    xaxis_title="Residual",
                    yaxis_title="Frequency",
                    height=400,
                )
                st.plotly_chart(fig, use_container_width=True)

                col1, col2 = st.columns(2)
                col1.metric("Mean Residual", f"{residuals.mean():.6f}")
                residual_std = residuals.std()
                col2.metric(
                    "Residual Std Dev",
                    f"{residual_std:.6f}" if pd.notna(residual_std) else "N/A",
                )

        st.divider()

        # Legacy downloads
        st.subheader("📥 Download Legacy Results")
        download_col1, download_col2 = st.columns(2)

        with download_col1:
            st.download_button(
                label="📊 Download Model Metrics",
                data=metrics_df.to_csv(index=False),
                file_name=f"{dataset}_model_metrics.csv",
                mime="text/csv",
                key=f"{dataset}_legacy_metrics_download",
            )
            st.download_button(
                label="📈 Download Forecast",
                data=forecast_df.to_csv(index=False),
                file_name=f"{dataset}_forecast.csv",
                mime="text/csv",
                key=f"{dataset}_legacy_forecast_download",
            )

        with download_col2:
            st.download_button(
                label="📌 Download Feature Importance",
                data=importance_df.to_csv(index=False),
                file_name=f"{dataset}_feature_importance.csv",
                mime="text/csv",
                key=f"{dataset}_legacy_importance_download",
            )
            if not prediction_df.empty:
                st.download_button(
                    label="🎯 Download Predictions",
                    data=prediction_df.to_csv(index=False),
                    file_name=f"{dataset}_actual_vs_predicted.csv",
                    mime="text/csv",
                    key=f"{dataset}_legacy_predictions_download",
                )

        st.divider()

        # One legacy insights block only. Do not label its score as validation
        # of V2, and avoid qualitative claims such as "Excellent".
        st.subheader("💡 Legacy Model Insights")
        st.info(
            "The metrics below belong to the original forecasting pipeline. "
            "Experimental Forecasting (V2) uses a separate observation-based "
            "evaluation. The two pipelines should not be compared as though "
            "they used the same evaluation protocol."
        )

        insight_parts = [
            f"**Legacy selected model:** {best_model}",
            (
                f"**Legacy R²:** {best_r2:.4f}"
                if pd.notna(best_r2)
                else "**Legacy R²:** unavailable"
            ),
            (
                f"**Legacy RMSE:** {best_rmse:.6f}"
                if pd.notna(best_rmse)
                else "**Legacy RMSE:** unavailable"
            ),
        ]
        if "MAPE" in best.index:
            best_mape = pd.to_numeric(best["MAPE"], errors="coerce")
            insight_parts.append(
                f"**Legacy MAPE:** {best_mape:.2f}%"
                if pd.notna(best_mape)
                else "**Legacy MAPE:** unavailable"
            )
        st.markdown("\n\n".join(insight_parts))


# =============================================================================
# Experimental Forecasting V2
# =============================================================================

st.divider()
st.header("🧪 Experimental Forecasting (V2)")

st.warning(
    """
    **Historical experiment — not a current forecast.**

    The available source data ends in December 2025. These projections
    represent the next 12 reporting observations after the last available
    observation, not the next 12 calendar days. They must not be interpreted
    as estimates of current October 2026 activity.
    """
)

v2_dir = V2_ROOT_DIR / dataset
v2_metrics_path = v2_dir / "model_metrics.csv"
v2_holdout_path = v2_dir / "holdout_predictions.csv"
v2_forecast_path = v2_dir / "future_forecast.csv"

if not all(
    path.exists()
    for path in [v2_metrics_path, v2_holdout_path, v2_forecast_path]
):
    st.info(
        "Experimental V2 results are not available for this dataset. "
        "Run `python -m src.forecasting_v2` to generate them."
    )
else:
    v2_metrics = load_csv(v2_dir, "model_metrics.csv")
    v2_holdout = load_csv(v2_dir, "holdout_predictions.csv")
    v2_forecast = load_csv(v2_dir, "future_forecast.csv")

    required_v2_metric_columns = {"Model", "MAE", "RMSE"}
    required_holdout_columns = {"Date", "Actual", "Predicted"}
    required_forecast_columns = {
        "Forecast Step",
        "Forecast",
        "Last Observed Date",
        "Horizon Definition",
    }

    missing_v2_metrics = required_v2_metric_columns - set(v2_metrics.columns)
    missing_holdout = required_holdout_columns - set(v2_holdout.columns)
    missing_forecast = required_forecast_columns - set(v2_forecast.columns)

    if v2_metrics.empty or v2_forecast.empty:
        st.warning("The experimental V2 files contain no results.")
    elif missing_v2_metrics or missing_forecast:
        problems = []
        if missing_v2_metrics:
            problems.append(
                "metrics missing: " + ", ".join(sorted(missing_v2_metrics))
            )
        if missing_forecast:
            problems.append(
                "forecast missing: " + ", ".join(sorted(missing_forecast))
            )
        st.error("Invalid V2 result files — " + "; ".join(problems) + ".")
    else:
        selected = v2_metrics.iloc[0]
        selected_model = str(selected["Model"])
        selected_rmse = pd.to_numeric(selected["RMSE"], errors="coerce")
        selected_mae = pd.to_numeric(selected["MAE"], errors="coerce")
        cutoff = str(v2_forecast["Last Observed Date"].iloc[0])

        if selected_model == "MeanBaseline":
            st.info(
                "Forecast method: mean baseline. The training-period mean "
                "is projected across all 12 reporting steps, so the line is "
                "flat by design. This is an experimental historical projection, "
                "not a current activity estimate."
            )

        k1, k2, k3, k4 = st.columns(4)
        k1.metric("Selected Model", selected_model)
        k2.metric(
            "Recursive Holdout RMSE",
            f"{selected_rmse:,.2f}" if pd.notna(selected_rmse) else "N/A",
        )
        k3.metric(
            "Recursive Holdout MAE",
            f"{selected_mae:,.2f}" if pd.notna(selected_mae) else "N/A",
        )
        k4.metric("Forecast Steps", len(v2_forecast))

        st.caption(f"Last observed date: {cutoff}")

        st.subheader("Recursive Holdout Evaluation")
        st.caption(
            "The final 12 reporting observations are predicted recursively: "
            "each prediction is fed into the next step without using the "
            "actual target from the holdout as future input."
        )
        st.dataframe(
            v2_metrics,
            use_container_width=True,
            hide_index=True,
        )

        if not v2_holdout.empty and not missing_holdout:
            holdout_plot = v2_holdout.copy()
            holdout_plot["Date"] = pd.to_datetime(
                holdout_plot["Date"], errors="coerce"
            )
            holdout_plot = holdout_plot.dropna(subset=["Date"])
            if not holdout_plot.empty:
                fig_holdout = px.line(
                    holdout_plot,
                    x="Date",
                    y=["Actual", "Predicted"],
                    markers=True,
                    title="Actual vs Predicted — Recursive Holdout",
                )
                fig_holdout.update_layout(
                    hovermode="x unified",
                    yaxis_title="Activity",
                    xaxis_title="Observed date",
                    height=450,
                )
                st.plotly_chart(fig_holdout, use_container_width=True)
        elif missing_holdout:
            st.warning(
                "The V2 holdout file is missing required columns: "
                + ", ".join(sorted(missing_holdout))
            )
        else:
            st.info("V2 holdout predictions are not available.")

        st.subheader("Next 12 Reporting Observations")
        forecast_plot = v2_forecast.copy()
        forecast_plot["Forecast Step"] = pd.to_numeric(
            forecast_plot["Forecast Step"], errors="coerce"
        )
        forecast_plot["Forecast"] = pd.to_numeric(
            forecast_plot["Forecast"], errors="coerce"
        )
        forecast_plot = forecast_plot.dropna(
            subset=["Forecast Step", "Forecast"]
        )

        if not forecast_plot.empty:
            fig_v2 = px.line(
                forecast_plot,
                x="Forecast Step",
                y="Forecast",
                markers=True,
                title="Experimental Historical Forecast",
            )
            fig_v2.update_layout(
                xaxis_title="Reporting observation step (not calendar days)",
                yaxis_title="Forecast activity",
                hovermode="x unified",
                height=400,
            )
            st.plotly_chart(fig_v2, use_container_width=True)
            st.dataframe(
                forecast_plot,
                use_container_width=True,
                hide_index=True,
            )
        else:
            st.warning("The V2 forecast file has no valid forecast rows.")

        st.subheader("Download Experimental V2 Results")
        d1, d2, d3 = st.columns(3)

        with d1:
            st.download_button(
                "Download V2 Metrics",
                data=v2_metrics.to_csv(index=False),
                file_name=f"{dataset}_v2_metrics.csv",
                mime="text/csv",
                key=f"{dataset}_v2_metrics_download",
            )

        with d2:
            st.download_button(
                "Download V2 Holdout",
                data=v2_holdout.to_csv(index=False),
                file_name=f"{dataset}_v2_holdout.csv",
                mime="text/csv",
                key=f"{dataset}_v2_holdout_download",
            )

        with d3:
            st.download_button(
                "Download V2 Forecast",
                data=v2_forecast.to_csv(index=False),
                file_name=f"{dataset}_v2_forecast.csv",
                mime="text/csv",
                key=f"{dataset}_v2_forecast_download",
            )


